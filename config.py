def get_render_order():
    """Возвращает порядок слоёв с учётом билета"""
    render_order = []
    user_inserted = False

    for i, layer_num in enumerate(YOUR_LAYERS, start=1):
        if USER_LAYER_POSITION == i and not user_inserted:
            render_order.append('user')
            user_inserted = True
        render_order.append(layer_num)

    if USER_LAYER_POSITION == len(YOUR_LAYERS) + 1 and not user_inserted:
        render_order.append('user')

    return render_order